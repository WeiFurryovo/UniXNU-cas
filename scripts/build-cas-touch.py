#!/usr/bin/env python3
"""Build the touch objects (build/cas-touch) that build-gop-legacy-display.py archives into the force-loaded display archive.

cas has umi's touch hardware: an ST FTM5 at I2C 0x49 on QUP1 SE13 (GSI DMA through GPI1), interrupt GPIO 39, reset
GPIO 38, AVDD switched by GPIO 69 and VDD from PM8150A L1 (cas live FDT). The driver is UniXNU-umi@3eb7257
package/touch (kits/cas/touch), which reached touch on umi hardware in its attempt 80; the cas changes are marked there.

This follows UniXNU-umi bringup/tools/build_umi_touch.py, which replays the framework's original HID qualification
(UniXNU scripts/build-sheng-hid-input.py) against umi's NativeHidInput.cpp. Here that qualification is carried inline
with every check kept, and runs against this board's previous kernel (ROOT.parent/kernel), which prelinks the same
original IOHIDFamily. The HID class is late-staged like the display's: HidInputProbe.cpp registers it.
"""
import hashlib
import json
import shutil
import struct
import subprocess
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
OUT = ROOT / 'build/cas-touch'
OUT.mkdir(parents=True, exist_ok=True)
SOURCE = ROOT / 'kits/cas/touch'
NL = chr(10)
sys.path.insert(0, str(ROOT / 'kits/XnuPrelink'))
from native_prelink import macho, backed_offset, exports


def run(cmd, **kw):
    return subprocess.check_output([str(x) for x in cmd], timeout=180, **kw)


def require(value, why):
    if not value:
        raise SystemExit('cas touch: ' + why)


def sha(path):
    return hashlib.sha256(Path(path).read_bytes()).hexdigest()


OBJCOPY = shutil.which('llvm-objcopy')
require(OBJCOPY, 'llvm-objcopy not found')

# 1. The reference: the board's previous kernel, its plan, and the original IOHIDFamily instructions inside it.
HID_TEXT_SHA = '7e4c5104814f2e773d5be13d092dec53ee44ba5a61a81264b229780406e86b72'
p = ROOT.parent / 'kernel/kernel.macho'
require(p.is_file(), 'no previous kernel at ' + str(p))
b = p.read_bytes()
plan = json.loads(p.with_suffix('.json').read_text())
m = macho(b)
require(hashlib.sha256(b).hexdigest() == plan['candidate_sha256'], 'reference kernel matches its plan')
require(plan['original_sha256'] == 'f18b4df865405f2a287b84977d7aca745e056d656d9fc9df1662970ce2969de7', 'the pinned donor')
require(plan['original_executable_sha256']['com.apple.iokit.IOHIDFamily'] == HID_TEXT_SHA, 'exact original HID reference')


def read(a, n):
    at = backed_offset(m['segments'], a, n, len(b))
    return b[at:at + n]


names = {n: a for a, ns in exports(b, m).items() for n in ns}
e = next(e for e in plan['extents'] if e['module'] == 'com.apple.iokit.IOHIDFamily' and e['segment'] == '__TEXT_EXEC')
require(hashlib.sha256(read(e['va'], e['size'])).hexdigest() == HID_TEXT_SHA, 'complete original HID instructions unchanged')

# umi's edge dispatch guard: the exact IOHIDFamily image bounds in this kernel.
bounds = {}
for segment, label in (('__TEXT_EXEC', 'TEXT'), ('__DATA_CONST', 'CONST')):
    x = next(x for x in plan['extents'] if x['module'] == 'com.apple.iokit.IOHIDFamily' and x['segment'] == segment)
    bounds[label] = (x['va'], x['va'] + x['size'])
(OUT / 'UmiHidEdgeABI.h').write_text('// Exact IOHIDFamily image bounds; no guessed runtime pointer.' + NL + ''.join(
    f'#define UMI_HID_{label}_{side} 0x{address:x}ULL' + NL
    for label, pair in bounds.items() for side, address in zip(('BEGIN', 'END'), pair)))

# 2. The original IOHIDDevice ABI (build-sheng-hid-input.py, unchanged checks).
vptr = 0xfffffff005d045c0
methods = struct.unpack('<207Q', read(vptr, 207 * 8))
base = struct.unpack('<168Q', read(names['__ZTV9IOService'] + 16, 168 * 8))
changed = [i for i in range(168) if methods[i] != base[i]]
require(changed == [0, 1, 7, 12, 14, 21, 23, 76, 81, 82, 86, 87, 91, 92, 93, 101, 132, 140], 'exact original HID native-base overrides')
require([i for i, a in enumerate(methods) if a == names['___cxa_pure_virtual']] == [180] and all(methods) and
        read(vptr + 207 * 8, 24) == bytes(24), 'exact original 207-slot abstract device')
require(read(0xfffffff004ad94f8, 0x20) == bytes.fromhex('fd7bbfa9fd0300912bd90094489100f008011791080000f9fd7bc1a8c0035fd6'),
        'original protected constructor and exact vptr store')
require(struct.unpack('<Q', read(0xfffffff005d00f10, 8))[0] == names['__ZN9IOServiceC2EPK11OSMetaClass'],
        'actual native protected constructor binding')
require(struct.unpack('<Q', read(0xfffffff005d00f18, 8))[0] == names['__ZN9IOServiceD2Ev'],
        'actual native protected destructor binding')
require(read(0xfffffff004ad9aec, 0x34) == bytes.fromhex(
    '680240f908a142f9e00313aae10314aa00013fd6680240f9603d003608d142f9e1630091e00313aa00013fd6a02d0035e00f40f9'),
    'original handleStart and report-descriptor ABI')
require(methods[181] == 0xfffffff004add0c4 and read(0xfffffff004add110, 28) == bytes.fromhex(
    '680240f9081543f9e00313aae20316aae30315aae40314aa00013fd6'), 'original handleReport forwards its arguments')
header = '''// Generated by scripts/build-cas-touch.py from the qualified original image; opaque private storage only.
#pragma once
#include <IOKit/IOService.h>
#include <IOKit/IOMemoryDescriptor.h>
class IOHIDDevice : public IOService {
 OSDeclareAbstractStructors(IOHIDDevice)
 unsigned char originalPrivate[0xd0-sizeof(IOService)];
public:
 using IOService::setProperty;
 IOReturn Dispatch(IORPC) override;
 void free() override;
 bool init(OSDictionary *properties=nullptr) override;
 bool setProperty(const OSSymbol *,OSObject *) override;
 bool willTerminate(IOService *,IOOptionBits) override;
 IOReturn configureReport(IOReportChannelList *,IOReportConfigureAction,void *,void *) override;
 IOReturn updateReport(IOReportChannelList *,IOReportUpdateAction,void *,void *) override;
 bool start(IOService *) override;
 void stop(IOService *) override;
 bool handleOpen(IOService *,IOOptionBits,void *) override;
 void handleClose(IOService *,IOOptionBits) override;
 bool handleIsOpen(const IOService *) const override;
 bool matchPropertyTable(OSDictionary *,SInt32 *) override;
 IOReturn message(UInt32,IOService *,void *) override;
 IOReturn newUserClient(task_t,void *,UInt32,OSDictionary *,IOUserClient **) override;
'''
for i in range(168, 207):
    if i == 171:
        header += ' virtual OSString *newTransportString() const;' + NL
    elif i == 173:
        header += ' virtual OSString *newProductString() const;' + NL
    elif i == 180:
        header += ' virtual IOReturn newReportDescriptor(IOMemoryDescriptor **) const=0;' + NL
    elif i == 181:
        header += ' virtual IOReturn handleReport(IOMemoryDescriptor *,unsigned,IOOptionBits);' + NL
    else:
        header += f' virtual __attribute__((deprecated("Unqualified prototype: never call from source"))) void opaque{i}();' + NL
header += '};' + NL + 'static_assert(sizeof(IOHIDDevice)==0xd0,"Original device instance size");' + NL
(OUT / 'OriginalHidDeviceABI.h').write_text(header)

# 3. The sources, with the kernel's C++ recipe (IOPlatformExpert's record), as umi's compile_from replays it.
record = json.loads((ROOT / 'build/xnu/ios-obj/DEVELOPMENT_ARM64_BCM2837/iokit/DEVELOPMENT/IOPlatformExpert.cpo.json')
                    .read_text().strip().rstrip(','))


def compile_from(source, obj, extra):
    command, suppressions, arguments, i = [], [], record['arguments'], 0
    while i < len(arguments):
        v = arguments[i]
        if v == record['file']:
            command.append(str(source))
        elif v == '-o':
            command += ['-o', str(obj)]
            i += 1
        elif v in ('-MF', '-MJ'):
            i += 1
        elif v == '-Xclang' and arguments[i + 1].startswith('-W'):
            i += 1
        elif v.startswith('-Wno-'):
            suppressions.append(v)      # the kernel's own suppressions, re-added after -Wall (as the display probe does)
        elif not v.startswith('-W') and v not in ('-MD', '-MP'):
            command.append(v)
        i += 1
    command += ['-Wall', '-Wextra', '-Werror', '-Wno-unused-parameter', '-Wno-c99-designator', '-Wno-reorder-init-list',
                '-Wno-deprecated-enum-enum-conversion', '-Wno-missing-designated-field-initializers',
                '-mgeneral-regs-only', '-I', str(record['directory']), *extra, *suppressions]
    obj.with_suffix('.command.json').write_text(json.dumps(command, indent=2) + NL)
    result = subprocess.run(command, cwd=record['directory'], text=True, capture_output=True, timeout=300)
    obj.with_suffix('.log').write_text(result.stdout + result.stderr)
    require(result.returncode == 0, 'compiling ' + source.name + ' failed:' + NL + result.stdout + result.stderr)


includes = ['-I', str(OUT), '-I', str(SOURCE), '-I', str(ROOT / '.cache/xnu-work/osfmk')]
obj = OUT / 'NativeHidInput.o'
compile_from(SOURCE / 'NativeHidInput.cpp', obj, includes)

# 4. Its exact 207-entry vtable, the only qualified overrides, and every original import bound by address.
raw = obj.read_bytes()
om = macho(raw)
st = next(q for c, q, _ in om['commands'] if c == 2)
sy, count, strings, _ = struct.unpack_from('<4I', raw, st + 8)
symbols = []
for i in range(count):
    ix, kind, section, _, va = struct.unpack_from('<IBBHQ', raw, sy + i * 16)
    symbols.append((raw[strings + ix:raw.index(bytes(1), strings + ix)].decode(), va, kind))
vt = next(va for name, va, _ in symbols if name == '__ZTV14NativeHidInput')
relocations = {}
for segment in om['segments']:
    for sec in segment['sections']:
        if sec['va'] <= vt < sec['va'] + sec['size']:
            ro, rc = struct.unpack_from('<2I', raw, sec['command_offset'] + 56)
            for i in range(rc):
                offset, bits = struct.unpack_from('<2I', raw, ro + i * 8)
                if bits >> 27 & 1 and bits >> 28 == 0 and bits >> 25 & 3 == 3:
                    relocations[sec['va'] + offset] = symbols[bits & 0xffffff][0]
compiled = [relocations.get(vt + 16 + i * 8) for i in range(207)]
require(all(compiled) and vt + 16 + 207 * 8 not in relocations, 'compiled exact 207-slot vtable')
bindings = {'__ZN11IOHIDDeviceC2EPK11OSMetaClass': 0xfffffff004ad94f8, '__ZN11IOHIDDeviceD2Ev': 0xfffffff004ad9518,
            '__ZN11IOHIDDevice10gMetaClassE': 0xfffffff006ae6fa0, '__ZTV11IOHIDDevice': vptr - 16}
owned = []
for i, name in enumerate(compiled):
    if name.startswith(('__ZN14NativeHidInput', '__ZNK14NativeHidInput')):
        owned.append(i)
    elif '11IOHIDDevice' in name:
        bindings[name] = methods[i]
    else:
        require(i < 168 and names.get(name) == methods[i], 'actual inherited native method ' + str(i))
require(owned == [0, 1, 7, 14, 86, 87, 111, 171, 173, 180], 'only qualified HID methods overridden')
undefined = {n for n, _, k in symbols if k == 1 and '11IOHIDDevice' in n}
require(undefined == set(bindings), 'all and only actual original HID imports bound')
asm = OUT / 'hid-original-bindings.S'
asm.write_text(''.join(f'.globl {n}' + NL + f'.set {n}, {a:#x}' + NL for n, a in sorted(bindings.items())))
run(['xcrun', 'clang', '-target', 'arm64-apple-ios17.0', '-Werror', '-Wno-incompatible-sysroot', '-c', asm,
     '-o', OUT / 'hid-original-bindings.o'])
late = OUT / 'NativeHidInput.late.o'
run([OBJCOPY, '--remove-section=__DATA,__mod_init_func', '--globalize-symbol=__GLOBAL__sub_I_NativeHidInput.cpp', obj, late])


def code(data, image):
    s = next(s for g in image['segments'] for s in g['sections'] if s['name'] == '__text')
    return data[s['fileoff']:s['fileoff'] + s['size']]


require(code(raw, om) == code(late.read_bytes(), macho(late.read_bytes())), 'owned code unchanged by late staging')

# 5. The FTS driver and the HID start-up probe.
objects = [late, OUT / 'hid-original-bindings.o']
for name in ('UmiFtsTouch', 'HidInputProbe'):
    o = OUT / (name + '.o')
    compile_from(SOURCE / (name + '.cpp'), o, includes + ['-Wno-unused-function', '-Wno-misleading-indentation'])
    objects.append(o)
(OUT / 'build-report.json').write_text(json.dumps(dict(
    reference_kernel_sha256=plan['candidate_sha256'], original_hid_text_sha256=HID_TEXT_SHA,
    sources={str(q.relative_to(ROOT)): sha(q) for q in sorted(SOURCE.iterdir()) if q.is_file()},
    objects={str(q.relative_to(ROOT)): sha(q) for q in objects}, owned_slots=owned,
    bindings={n: hex(a) for n, a in bindings.items()}, runtime_qualified=False), indent=2) + NL)
print(f'cas touch: HID ABI qualified ({len(bindings)} bindings, owned {owned}); FTS driver and probe compiled')
