#!/usr/bin/env python3
"""Build build/native-legacy-display/libNativeLegacyDisplay.late.a for CONFIG_XNU_NATIVE_LEGACY_DISPLAY=y.

The CPU-presented display UniXNU-umi and UniXNU-alioth reach the Apple logo and Hello with: GopFramebuffer's
NativeLegacyDisplay (a subclass of the prelinked original IOMobileFramebufferLegacy that copies each compositor frame
into the firmware frame buffer), its NativeGOPPresenter, and the board half kits/cas/LegacyDisplayProbe.cpp, which the
bsd_init and bsd_autoconf hooks of offline-component-load-probes.patch and offline-legacy-start.patch call.

This follows UniXNU-sheng@08cde20 scripts/build-gop-legacy-display.py, whose generated class header and bindings match
the framework's GopFramebuffer 33e941a, with the board coupling removed the way UniXNU-alioth@520581a removes it: only
the display path is built, plus the AppleKeyStore stand-in and the touch objects of build-cas-touch.py. Every class layout check, the 358-entry vtable check and every absolute address check is
kept and runs against this board's previous kernel (ROOT.parent/kernel), which carries the original family unchanged.

Host differences: the drivers compile through scripts/cas-arm-driver.py (clang 24 warning), llvm-objcopy and llvm-ar come from PATH (no Homebrew), and the audit's pruned QEMU observation of the
original class is carried over by its recorded hash, the way the audit itself provides for.
"""
import hashlib
import json
import shutil
import struct
import subprocess
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
OUT = ROOT / 'build/native-legacy-display'
OUT.mkdir(parents=True, exist_ok=True)
sys.path.insert(0, str(ROOT / 'kits/XnuPrelink'))
from native_prelink import macho, backed_offset, exports


def run(cmd, **kw):
    return subprocess.check_output([str(x) for x in cmd], timeout=180, **kw)


def require(value, why):
    if not value:
        raise SystemExit('legacy display: ' + why)


def sha(path):
    return hashlib.sha256(Path(path).read_bytes()).hexdigest()


OBJCOPY = shutil.which('llvm-objcopy')
AR = shutil.which('llvm-ar') or 'ar'
require(OBJCOPY, 'llvm-objcopy not found')
PROBE_SOURCE = ROOT / 'kits/cas/LegacyDisplayProbe.cpp'
KEYSTORE_SOURCE = ROOT / 'kits/cas/KeyStoreProbe.cpp'
CPUFREQ_SOURCE = ROOT / 'kits/cas/CpuFreqProbe.cpp'
BUTTONS_SOURCE = ROOT / 'kits/cas/ButtonProbe.cpp'

# 1. The reference candidate: the board's previous kernel, under the name the audit and the bindings read.
reference = ROOT.parent / 'kernel/kernel.macho'
require(reference.is_file(), 'no previous kernel at ' + str(reference) + '; build the kernel once without the display')
prelink = ROOT / 'build/xnu-prelink'
prelink.mkdir(parents=True, exist_ok=True)
candidate = prelink / 'native-owner-mobile-graphics-candidate.macho'
candidate.unlink(missing_ok=True)
shutil.copyfile(reference, candidate)
shutil.copyfile(reference.with_suffix('.json'), candidate.with_suffix('.json'))

# 2. The original class ABI, re-derived from that kernel.
analysis = ROOT / 'build/display-analysis/mobile-graphics-legacy-abi.json'
if not analysis.exists():
    analysis.parent.mkdir(parents=True, exist_ok=True)
    analysis.write_text(json.dumps({'runtime_metadata_checkpoint_sha256':
                                    '3044c2beff552911605994c0dc7aa73182066cbb5aed0b396999ceeb5a96da2b'}) + '\n')
print(run(['python3', ROOT / 'scripts/audit-mobile-graphics-legacy.py'], text=True), end='')
audit = json.loads(analysis.read_text())
pure = audit['abstract_slots']
methods = audit['methods']

header = '''// SPDX-License-Identifier: BSD-2-Clause-Patent
// Generated by scripts/build-gop-legacy-display.py (from UniXNU-sheng@08cde20). Do not edit.
// Opaque ABI storage for the exact original class, not source-level access to its private fields.
#pragma once
#include <IOKit/IOService.h>
#include <libkern/libkern.h>
struct OriginalLegacySwapRequest;
class IOMobileFramebufferLegacy : public IOService {
 OSDeclareAbstractStructors(IOMobileFramebufferLegacy)
 unsigned char originalPrivate[0x18a0-sizeof(IOService)];
public:
 void installBootDimensions(uint32_t width,uint32_t height) {
  *reinterpret_cast<uint32_t *>(reinterpret_cast<unsigned char *>(this)+5808)=width;
  *reinterpret_cast<uint32_t *>(reinterpret_cast<unsigned char *>(this)+5812)=height;
 }
 const OriginalLegacySwapRequest *pendingSwapRequest() const {
  const OriginalLegacySwapRequest *request=nullptr;
  memcpy(&request,reinterpret_cast<const unsigned char *>(this)+5480,sizeof(request));return request;
 }
 // Tail queue: head at +5480, tail pointer at +5488, each request's next at +2960 and previous-link at +2968.
 bool activateOnlyPendingSwap(const OriginalLegacySwapRequest *request) {
  auto self=reinterpret_cast<unsigned char *>(this);
  auto bytes=reinterpret_cast<const unsigned char *>(request);
  const void *current=nullptr,*head=nullptr,*tail=nullptr,*next=nullptr,*previous=nullptr;
  memcpy(&current,self+5472,8);memcpy(&head,self+5480,8);memcpy(&tail,self+5488,8);
  if(!request || current || head!=request)return false;
  memcpy(&next,bytes+2960,8);memcpy(&previous,bytes+2968,8);
  if(previous!=self+5480)return false;
  if(next) {
   const void *link=self+5480;
   memcpy(const_cast<unsigned char *>(reinterpret_cast<const unsigned char *>(next))+2968,&link,8);
  } else if(tail!=bytes+2960)return false;
  memcpy(self+5472,&request,8);
  if(next) {memcpy(self+5480,&next,8);}
  else {const void *empty=nullptr,*emptyTail=self+5480;memcpy(self+5480,&empty,8);memcpy(self+5488,&emptyTail,8);}
  return true;
 }
 void free() override;
 bool init(OSDictionary *properties=nullptr) override;
 IOReturn setProperties(OSObject *) override;
 void systemWillShutdown(IOOptionBits) override;
 IOService *probe(IOService *,SInt32 *) override;
 bool start(IOService *) override;
 void stop(IOService *) override;
 IOWorkLoop *getWorkLoop() const override;
 IOReturn newUserClient(task_t,void *,UInt32,IOUserClient **) override;
 IOReturn setPowerState(unsigned long,IOService *) override;
'''
named = {184: ' virtual bool isMainDisplay();\n', 188: ' virtual IOReturn getDotPitch(uint32_t *);\n',
         213: ' virtual IOReturn supportedFrameInfo(uint32_t,uint32_t *,char *,uint32_t *)=0;\n',
         249: ' virtual void getDisplayDimensions(uint32_t *,uint32_t *);\n', 290: ' virtual void kickSwapQueue();\n',
         296: ' virtual bool validateSwap(const OriginalLegacySwapRequest *);\n',
         295: ' virtual void completeCurrentSwap();\n',
         337: ' virtual IOReturn collectCompletionReports(uint32_t,void *,uint32_t *,uint32_t)=0;\n',
         288: ' virtual bool startHardware();\n', 301: ' virtual bool getRefreshAttributes(uint64_t *,bool);\n'}
for i in range(168, 358):
    if i in named:
        header += named[i]
    elif i in pure:
        header += f' virtual __attribute__((noreturn)) void opaque{i}()=0;\n'
    else:
        header += f' virtual __attribute__((deprecated("Unclassified ABI: never call from source"))) void opaque{i}();\n'
header += '};\nstatic_assert(sizeof(IOMobileFramebufferLegacy)==0x18a0,"Actual original instance extent");\n'
(OUT / 'OriginalLegacyFramebufferABI.h').write_text(header)

# 3. The owned backend, with the kernel's own flags, and its exact 358-entry vtable.
print(run(['python3', ROOT / 'scripts/cas-arm-driver.py', 'NativeLegacyDisplay'], text=True), end='')
obj = OUT / 'NativeLegacyDisplay.o'
raw = obj.read_bytes()
image = macho(raw)
symtab = next(p for c, p, _ in image['commands'] if c == 2)
symoff, count, stroff, _ = struct.unpack_from('<4I', raw, symtab + 8)
symbols = []
for i in range(count):
    ix, kind, _, _, va = struct.unpack_from('<IBBHQ', raw, symoff + i * 16)
    symbols.append((raw[stroff + ix:raw.index(b'\0', stroff + ix)].decode(), va, kind))
vtable = next(va for name, va, _ in symbols if name == '__ZTV19NativeLegacyDisplay')
relocations = {}
for segment in image['segments']:
    for section in segment['sections']:
        if section['va'] <= vtable < section['va'] + section['size']:
            ro, rc = struct.unpack_from('<2I', raw, section['command_offset'] + 56)
            for i in range(rc):
                offset, bits = struct.unpack_from('<2I', raw, ro + i * 8)
                if bits >> 27 & 1 and bits >> 28 == 0 and bits >> 25 & 3 == 3:
                    relocations[section['va'] + offset] = symbols[bits & 0xffffff][0]
compiled = [relocations.get(vtable + 16 + i * 8) for i in range(358)]
require(all(compiled) and vtable + 16 + 358 * 8 not in relocations, 'exact owned 358-entry vtable')

old = candidate.read_bytes()
old_image = macho(old)
names = {n: v for v, group in exports(old, old_image).items() for n in group}


def read(va, n):
    at = backed_offset(old_image['segments'], va, n, len(old))
    return old[at:at + n]


bindings = {'__ZN25IOMobileFramebufferLegacyC2EPK11OSMetaClass': 0xfffffff0057865cc,
            '__ZN25IOMobileFramebufferLegacyD2Ev': 0xfffffff005786618,
            '__ZN25IOMobileFramebufferLegacy10gMetaClassE': 0xfffffff006b35940,
            '__ZTV25IOMobileFramebufferLegacy': int(audit['legacy_vptr'], 16) - 16}
OWNED = (0, 1, 7, 14, 84, 86, 87, 141, 155, 184, 188, 288, 290, 296, 301)
owned, native = [], []
for i, name in enumerate(compiled):
    expected = int(methods[i]['address'], 16)
    if name.startswith(('__ZN19NativeLegacyDisplay', '__ZNK19NativeLegacyDisplay')):
        owned.append(i)
        require(i in OWNED or i in pure, 'only qualified own methods and guarded leaves override')
    elif '25IOMobileFramebufferLegacy' in name:
        require(i not in pure, 'no unresolved original abstract backend target')
        bindings[name] = expected
    else:
        require(i < 168 and names.get(name) == expected, 'actual inherited native base symbol ' + str(i))
        native.append(i)
require(owned == sorted(list(OWNED) + pure), 'exact owned method set')
undefined = {n for n, _, k in symbols if k == 1 and 'IOMobileFramebufferLegacy' in n}
require(undefined == set(bindings), 'all and only actual original-class imports qualified')

# The original IOSurface getters the backend calls, each a single load and return.
for name, address, field, wide in [
        ('descriptor', 0xfffffff004b9ead0, 48, True), ('width', 0xfffffff004b9ebbc, 88, True),
        ('height', 0xfffffff004b9ebc4, 96, True), ('stride', 0xfffffff004b9ebd4, 104, True),
        ('allocation', 0xfffffff004b9ebfc, 144, True), ('format', 0xfffffff004b9ebac, 128, False),
        ('planes', 0xfffffff004b9ebf4, 152, False)]:
    expected = (0xf9400000 if wide else 0xb9400000) | ((field // (8 if wide else 4)) << 10)
    require(read(address, 8) == struct.pack('<2I', expected, 0xd65f03c0), 'exact original surface getter ' + name)
    bindings['_native_legacy_surface_' + name] = address
# The original vsync sender and setDisplayRefreshProperties (used only with sheng-vsync).
require(read(0xfffffff005796720, 16) == bytes.fromhex('ff0302d1fd7b07a9fdc30191a0831ff8') and
        read(0xfffffff005796830, 4) == bytes.fromhex('08ed4af9') and
        read(0xfffffff00579685c, 16) == bytes.fromhex('e2230091c3008052240080521684ff97') and
        read(0xfffffff005795fbc, 4) == bytes.fromhex('0ab182d2'), 'original vsync sender')
bindings['_native_legacy_vsync_notify'] = 0xfffffff005796720
require(int(methods[301]['address'], 16) == 0xfffffff00579ea5c and
        read(0xfffffff00579ea68, 8) == bytes.fromhex('888888d28888a0f2') and
        read(0xfffffff00579ec54, 4) == bytes.fromhex('08b544f9'), 'original slot-301 refresh words')
require(read(0xfffffff00579ebb8, 16) == bytes.fromhex('ff0302d1fd7b07a9fdc30191a0031ff8') and
        read(0xfffffff00579ed54, 16) == bytes.fromhex('086540f90173ff90218c0c9100013fd6'),
        'original setDisplayRefreshProperties')
bindings['_native_legacy_set_refresh_properties'] = 0xfffffff00579ebb8


def branch(pc):
    word = struct.unpack('<I', read(pc, 4))[0]
    require(word & 0xfc000000 == 0x94000000, 'actual protected base call')
    value = word & 0x3ffffff
    return pc + 4 * (value - (1 << 26) if value & (1 << 25) else value)


require(branch(0xfffffff0057865fc) == 0xfffffff00577b510 and branch(0xfffffff005786630) == 0xfffffff00577b55c,
        'original protected Legacy C2/D2 call their original Service bases')
require(read(0xfffffff005787ef8, 16) == bytes.fromhex('080040f9088144f900013fd6e0000037'),
        'original bool start_hardware() call and result check')
getter = int(methods[249]['address'], 16)
for offset, field in [(0x30, 5808), (0x58, 5812)]:
    require(struct.unpack('<I', read(getter + offset, 4))[0] == 0xb9400000 | ((field // 4) << 10) | (8 << 5) | 8,
            'actual original width/height getter fields')
require(int(methods[295]['address'], 16) == 0xfffffff005795b88 and
        read(0xfffffff005795b98, 16) == bytes.fromhex('e00740f9280080520101001272d3ff97'),
        'original slot-295 passes true to the normal completion body')
require(read(0xfffffff00578aa7c, 24) == bytes.fromhex('080040f9084545f9030080d2e20303aa0400805200013fd6'),
        'original completion calls optional report slot 337 with null outputs')
require(read(0xfffffff005777e9c, 16) == bytes.fromhex('080040f908e142f900013fd6c0000036'),
        'original isMainDisplay dispatch')

assembly = OUT / 'original-bindings.S'
assembly.write_text(''.join(f'.globl {name}\n.set {name}, {va:#x}\n' for name, va in sorted(bindings.items())))
run(['xcrun', 'clang', '-target', 'arm64-apple-ios17.0', '-Werror', '-Wno-incompatible-sysroot', '-c', assembly,
     '-o', OUT / 'original-bindings.o'])


def code(data, info):
    section = next(s for g in info['segments'] for s in g['sections'] if s['name'] == '__text')
    return data[section['fileoff']:section['fileoff'] + section['size']]


def stage_late(source, destination, initializer):
    """The class registers when the probe runs its initializer between preModLoad and postModLoad."""
    run([OBJCOPY, '--remove-section=__DATA,__mod_init_func', '--globalize-symbol=' + initializer, source, destination])
    require(code(source.read_bytes(), macho(source.read_bytes())) ==
            code(destination.read_bytes(), macho(destination.read_bytes())), 'late staging changed code of ' + source.name)


late = OUT / 'NativeLegacyDisplay.late.o'
stage_late(obj, late, '__GLOBAL__sub_I_NativeLegacyDisplay.cpp')

# 4. The board half, with the kernel's C++ recipe (IOPlatformExpert's record), as alioth compiles it.
record = json.loads((ROOT / 'build/xnu/ios-obj/DEVELOPMENT_ARM64_BCM2837/iokit/DEVELOPMENT/IOPlatformExpert.cpo.json')
                    .read_text().strip().rstrip(','))
probe_obj = OUT / 'LegacyDisplayProbe.o'
command, suppressions, arguments, i = [], [], record['arguments'], 0
while i < len(arguments):
    value = arguments[i]
    if value == record['file']:
        command.append(str(PROBE_SOURCE))
    elif value == '-o':
        command += ['-o', str(probe_obj)]
        i += 1
    elif value in ('-MF', '-MJ'):
        i += 1
    elif value == '-Xclang' and arguments[i + 1].startswith('-W'):
        i += 1
    elif value.startswith('-Wno-'):
        suppressions.append(value)
    elif not value.startswith(('-W', '-DXNU_BOOT_PROGRESS=')) and value not in ('-MD', '-MP'):
        command.append(value)
    i += 1
command += ['-mgeneral-regs-only', '-Wall', '-Wextra', '-Werror', '-Wno-unused-parameter',
            '-Wno-c99-designator', '-Wno-reorder-init-list', '-Wno-deprecated-enum-enum-conversion',
            '-Wno-missing-designated-field-initializers', '-I', str(record['directory']), '-I', str(ROOT / '.cache/xnu-work/osfmk'), '-I', str(OUT)] + suppressions
run(command, cwd=record['directory'])
(OUT / 'probe-compile-command.json').write_text(json.dumps(command, indent=2) + '\n')

# The AppleKeyStore stand-in, as alioth builds it: the probe (same recipe as the display probe) supplies the board
# callbacks and registers the component's class, whose initialiser is staged like the display's. A static archive is
# only pulled in when something references it, so the component's own library is not enough.
keystore_probe_obj = OUT / 'KeyStoreProbe.o'
run([str(KEYSTORE_SOURCE) if x == str(PROBE_SOURCE) else str(keystore_probe_obj) if x == str(probe_obj) else x
     for x in command], cwd=record['directory'])
# The CPU frequency vote (UniXNU-alioth's CpuFreqProbe), same recipe; the display probe calls it, the banner polls it.
cpufreq_obj = OUT / 'CpuFreqProbe.o'
run([str(CPUFREQ_SOURCE) if x == str(PROBE_SOURCE) else str(cpufreq_obj) if x == str(probe_obj) else x
     for x in command], cwd=record['directory'])
# The power and volume keys (UniXNU-alioth's ButtonProbe), same recipe; the display probe starts its thread.
buttons_obj = OUT / 'ButtonProbe.o'
run([str(BUTTONS_SOURCE) if x == str(PROBE_SOURCE) else str(buttons_obj) if x == str(probe_obj) else x
     for x in command], cwd=record['directory'])
keystore = ROOT / 'build/apple-key-store-state/NativeKeyStoreEvents.o'
require(keystore.is_file(), 'no NativeKeyStoreEvents.o; component:AppleKeyStoreState must run before this script')
keystore_late = OUT / 'NativeKeyStoreEvents.late.o'
stage_late(keystore, keystore_late, '__GLOBAL__sub_I_NativeKeyStoreEvents.cpp')

# 5. The owned presenter, staged the same way.
print(run(['python3', ROOT / 'scripts/cas-arm-driver.py', 'NativeGOPPresenter'], text=True), end='')
presenter = ROOT / 'build/native-gop-presenter/NativeGOPPresenter.o'
require(presenter.is_file(), 'the driver recipe left no NativeGOPPresenter.o')
presenter_late = OUT / 'NativeGOPPresenter.late.o'
stage_late(presenter, presenter_late, '__GLOBAL__sub_I_NativeGOPPresenter.cpp')

archive = OUT / 'libNativeLegacyDisplay.late.a'
archive.unlink(missing_ok=True)
# The touch objects (scripts/build-cas-touch.py, which runs before this script): nothing references them but the probe,
# so they ride in this force-loaded archive, as alioth's touch does.
touch = ROOT / 'build/cas-touch'
touch_objects = [touch / name for name in ('NativeHidInput.late.o', 'hid-original-bindings.o', 'UmiFtsTouch.o', 'HidInputProbe.o')]
require(all(o.is_file() for o in touch_objects), 'no touch objects; build-cas-touch.py must run before this script')
run([AR, 'rcs', archive, late, OUT / 'original-bindings.o', probe_obj, presenter_late, keystore_probe_obj, keystore_late, cpufreq_obj, buttons_obj,
     *touch_objects])
# build-xnu-4k-baseline.sh rehashes these sources (relative to the tree) before linking the archive.
sources = [ROOT / 'drivers/GopFramebuffer/NativeLegacyDisplay.cpp', ROOT / 'drivers/GopFramebuffer/NativeLegacyRequest.h',
           ROOT / 'drivers/GopFramebuffer/NativeGOPPresenter.cpp', ROOT / 'drivers/GopFramebuffer/NativeGOPWire.h',
           PROBE_SOURCE, KEYSTORE_SOURCE, CPUFREQ_SOURCE, BUTTONS_SOURCE, ROOT / 'kits/cas/ButtonsCore.h', *sorted((ROOT / 'kits/cas/touch').glob('*.[ch]*')), ROOT / 'drivers/AppleKeyStoreState/NativeKeyStoreEvents.cpp',
           OUT / 'OriginalLegacyFramebufferABI.h']
(OUT / 'build-report.json').write_text(json.dumps(dict(
    source_sha256={str(path.relative_to(ROOT)): sha(path) for path in sources},
    original_candidate_sha256=sha(candidate), original_audit_sha256=sha(analysis),
    compiled_object_sha256=sha(obj), late_object_sha256=sha(late), probe_object_sha256=sha(probe_obj),
    presenter_object_sha256=sha(presenter_late), keystore_object_sha256=sha(keystore_late),
    touch_object_sha256={o.name: sha(o) for o in touch_objects}, archive_sha256=sha(archive),
    bindings={name: hex(value) for name, value in bindings.items()},
    virtual_entries=358, owned_entries=owned, inherited_native_entries=native,
    original_instructions_modified=False, runtime_qualified=False), indent=2) + '\n')
print(f'legacy display: {len(bindings)} original bindings, {len(owned)} owned slots; archive built')
