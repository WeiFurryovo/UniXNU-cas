#!/usr/bin/env python3
"""Link stubs for names a selected driver imports from a layer this board leaves off (CONFIG_XNU_EXTRA_LD_ARCHIVES).

NativeUfs calls boot_progress_poll() while it waits for the device, declared weak_import (NativeUfs.cpp:90), but
the kernel link has no undefined-weak allowance and CONFIG_XNU_BOOT_PROGRESS is off here. An empty poll is what the
off state means. The archive is linked without -force_load, so the stub only fills an otherwise undefined name.
"""
from pathlib import Path
import subprocess

ROOT = Path(__file__).resolve().parents[1]
out = ROOT / 'build/link-stubs'
out.mkdir(parents=True, exist_ok=True)
source = out / 'LinkStubs.c'
source.write_text('''// Generated by scripts/build-link-stubs.py.
void boot_progress_poll(void);
void boot_progress_poll(void)
{
}
''')
subprocess.run(['xcrun', '--sdk', 'iphoneos', 'clang', '-arch', 'arm64', '-mkernel', '-miphoneos-version-min=17.0', '-Os',
                '-c', source, '-o', out / 'LinkStubs.o'], check=True)
(out / 'libLinkStubs.a').unlink(missing_ok=True)
subprocess.run(['xcrun', 'ar', 'rcs', out / 'libLinkStubs.a', out / 'LinkStubs.o'], check=True)
print('link stubs: boot progress poll archived')
