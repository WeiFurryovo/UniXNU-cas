#!/usr/bin/env python3
"""Link stubs for the read-only UFS probe image (CONFIG_XNU_EXTRA_LD_ARCHIVES).

NativeUfs is compiled with NATIVE_VERIFIED_BLOCK, so it imports the VerifiedRoot verifier and the boot progress
poll. The probe image (native-ufs-probe=10) uses neither: the verifier needs the owner-signed OS policy that only
exists once the root image is built. These stubs refuse every verification, so a root built from this image can
never be published; drop this archive when CONFIG_XNU_VERIFIED_ROOT_PROBE supplies the real verifier.
"""
from pathlib import Path
import subprocess

ROOT = Path(__file__).resolve().parents[1]
out = ROOT / 'build/link-stubs'
out.mkdir(parents=True, exist_ok=True)
source = out / 'LinkStubs.c'
source.write_text('''// Generated by scripts/build-link-stubs.py: refuse-everything verifier for the UFS probe image.
#include <stddef.h>
#include <stdint.h>
void boot_progress_poll(void);
void boot_progress_poll(void)
{
}
// A zero policy count makes NativeUfs refuse before it reads the key or calls the verifier.
const uint8_t verified_root_key[512] = {0};
const uint64_t verified_root_policies[64] = {0};
const uint64_t verified_root_policy_count = 0;
const uint64_t vr_xnu_crypto[8] = {0};
int vr_open(void);
int vr_open(void)
{
\treturn -1;
}
int vr_verify_block(void);
int vr_verify_block(void)
{
\treturn -1;
}
''')
subprocess.run(['xcrun', '--sdk', 'iphoneos', 'clang', '-arch', 'arm64', '-mkernel', '-miphoneos-version-min=17.0', '-Os',
                '-c', source, '-o', out / 'LinkStubs.o'], check=True)
(out / 'libLinkStubs.a').unlink(missing_ok=True)
subprocess.run(['xcrun', 'ar', 'rcs', out / 'libLinkStubs.a', out / 'LinkStubs.o'], check=True)
print('link stubs: refuse-everything verifier and boot progress poll archived')
